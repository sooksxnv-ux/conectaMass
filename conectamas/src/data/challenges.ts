export function getLevelInfo(points: number): LevelInfo {
  if (points < 150) {
    return {
      name: 'Primeros pasos',
      minPoints: 0,
      maxPoints: 150,
      nextLevelName: 'Compañeros',
      badgeLevel: 'Nivel 1 🌱',
    };
  } else if (points < 350) {
    return {
      name: 'Compañeros',
      minPoints: 150,
      maxPoints: 350,
      nextLevelName: 'Equipo unido',
      badgeLevel: 'Nivel 2 🌟',
    };
  } else if (points < 600) {
    return {
      name: 'Equipo unido',
      minPoints: 350,
      maxPoints: 600,
      nextLevelName: 'Agentes de inclusión',
      badgeLevel: 'Nivel 3 🚀',
    };
  } else {
    return {
      name: 'Agentes de inclusión',
      minPoints: 600,
      maxPoints: 1000,
      nextLevelName: undefined,
      badgeLevel: 'Nivel 4 👑',
    };
  }
}

